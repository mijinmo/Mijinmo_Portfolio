def card(p, featured=False):
    title = t(p['title'])
    if p['image']:
        media = img(p['image'], t((title + ' · 项目画面', title + ' — project image')))
    else:
        media = f'<div class="controller-art" aria-hidden="true"><span>↔</span><span>MICRO:BIT × UNITY</span></div>'
    destination = t(p['url'])
    if destination:
        media = f'<a class="project-image" href="{e(asset(destination) if destination.startswith("Files/") else destination)}" aria-label="{e(title)}">{media}</a>'
    else:
        media = f'<div class="project-image">{media}</div>'
    archive = f'<span class="archive-tag">{t(("学生作品 · 已停止维护", "Student work · No longer maintained"))}</span>' if p['archived'] else ''
    video = f'<details class="video-details"><summary>{t(("观看演示视频", "Watch demonstration"))}</summary><video controls preload="none" playsinline width="640" height="480" aria-label="{e(title)}"><source src="{asset("Files/IMG_5372.MOV")}">{t(("浏览器无法播放时，请下载视频。", "If playback is unsupported, download the video."))}</video></details>' if p['id'] == 'balance' else ''
    return f'''<article class="project-card" id="{p['id']}" data-category="{p['category']}"><header><span class="date">{e(t(p['date']))}</span><h2>{e(title)}</h2></header>{media}
<div class="project-copy">{md('projects/' + p['id'])}{video}<div class="project-end">{link(p['url'], p['platform'], 'button') if p['url'] else ''}<p>{archive}</p></div></div></article>'''

