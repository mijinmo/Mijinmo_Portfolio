def write(path, content):
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix('.html.tmp')
    temporary.write_text(content + '\n', encoding='utf-8', newline='\n')
    temporary.replace(target)

def build():
    global LANG
    output = {}
    for LANG in ('zh', 'en'):
        for page, render in zip(PAGES, [home, projects, research, art, about, journey]):
            output[('en/' if LANG == 'en' else '') + page] = shell(page, render())
    redirects = {'index_cn.html': 'index.html', 'index_2.html': 'projects.html',
                 'publicans.html': 'research.html#scented-days', 'Blogs.html': 'research.html',
                 'neuroscience.html': 'research.html#neuroscience', 'course_project.html': 'research.html#fmri',
                 'alt_games.html': 'projects.html#experimental', 'ref.html': 'index.html', 'blog8.html': 'Journey_Cam_Analysis.html'}
    for old, target in redirects.items():
        output[old] = f'<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta http-equiv="refresh" content="0;url={target}"><title>页面已迁移 — Sihao Chen</title></head><body><p>页面已整理至新位置。<a href="{target}">继续浏览 / Continue</a></p></body></html>'
    for path, html in output.items():
        write(path, html)
    print(f'Built {len(PAGES) * 2} content pages and {len(redirects)} legacy redirects.')

if __name__ == '__main__':
    build()
