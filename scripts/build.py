def e(value):
    return escape(str(value), quote=True)

def asset(path):
    return ('../' if LANG == 'en' else '') + quote(path, safe='/')

def image_size(path):
    """Read dimensions without a third-party image dependency."""
    with (ROOT / path).open('rb') as f:
        head = f.read(24)
        if head.startswith(b'\x89PNG'):
            return struct.unpack('>II', head[16:24])
        if head.startswith(b'GIF'):
            return struct.unpack('<HH', head[6:10])
        if head.startswith(b'RIFF') and head[8:12] == b'WEBP':
            f.seek(0)
            data = f.read(32)
            if data[12:16] == b'VP8 ':
                width, height = struct.unpack('<HH', data[26:30])
                return width & 0x3fff, height & 0x3fff
            if data[12:16] == b'VP8X':
                return int.from_bytes(data[24:27], 'little') + 1, int.from_bytes(data[27:30], 'little') + 1
            if data[12:16] == b'VP8L':
                bits = int.from_bytes(data[21:25], 'little')
                return (bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1
        if head.startswith(b'\xff\xd8'):
            f.seek(2)
            while True:
                byte = f.read(1)
                if not byte:
                    break
                if byte != b'\xff':
                    continue
                marker = f.read(1)
                while marker == b'\xff':
                    marker = f.read(1)
                if marker in (b'\xd8', b'\xd9'):
                    continue
                length = struct.unpack('>H', f.read(2))[0]
                if marker[0] in (0xC0, 0xC1, 0xC2, 0xC3):
                    _, height, width = struct.unpack('>BHH', f.read(5))
                    return width, height
                f.seek(length - 2, 1)
    raise ValueError(f'Unsupported image: {path}')

def img(path, alt, eager=False, css=''):
    width, height = image_size(path)
    return f'<img src="{asset(path)}" alt="{e(alt)}" width="{width}" height="{height}" loading="{"eager" if eager else "lazy"}" decoding="async" class="{css}">'

def link(url, label, css='text-link'):
    url = t(url)
    if url.startswith(('Files/', 'images/')):
        url = asset(url)
    return f'<a class="{css}" href="{e(url)}">{e(t(label))}</a>'

def section_heading(number, title, extra=''):
    return f'<div class="section-heading"><h2>{e(t(title))}</h2></div>'

def heading(title, content_key):
    return f'<header class="page-heading major"><h1>{e(t(title))}</h1>{md(content_key)}</header>'

